    const data = await response.json();
    if (!response.ok) return;
    guestOrderMeta = {
      orderId: data.orderId,
      token,
      pdfUrl: data.pdfUrl || null
    };
    memberReportMeta = null;
    activeTier = data.tier;
    latest = data.result;
